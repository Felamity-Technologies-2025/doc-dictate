import {
  DocumentModel,
  TranscriptionResponse,
  BackendHealth,
  ExportFormat,
  NewTemplateField,
  TemplateFieldUpdate,
  TemplateModel,
  TemplateSummary,
  TemplateUploadResult,
} from '../types';

const API_BASE = import.meta.env.VITE_API_BASE_URL || '';

/** URL of a picture extracted from a template (logos, banners...) */
export function templateImageUrl(templateId: string, imageId: string): string {
  return `${API_BASE}/api/templates/${encodeURIComponent(templateId)}/images/${encodeURIComponent(imageId)}`;
}

export class ApiService {
  /**
   * Check backend health and configuration
   */
  static async checkHealth(): Promise<BackendHealth | null> {
    try {
      const response = await fetch(`${API_BASE}/api/health`, {
        method: 'GET',
        headers: { 'Accept': 'application/json' },
      });
      if (!response.ok) return null;
      return await response.json();
    } catch {
      return null;
    }
  }

  /**
   * Upload an audio blob/file for transcription to the Python Flask backend
   */
  static async transcribeAudio(
    audioBlob: Blob,
    filename = 'recording.webm',
    language = 'en-US',
    engine = 'google'
  ): Promise<TranscriptionResponse> {
    const formData = new FormData();
    formData.append('audio', audioBlob, filename);
    formData.append('language', language);
    formData.append('engine', engine);

    const response = await fetch(`${API_BASE}/api/transcribe`, {
      method: 'POST',
      body: formData,
    });

    const data = await response.json().catch(() => ({
      success: false,
      error: `Server error HTTP ${response.status}`,
    }));

    if (!response.ok && !data.error) {
      data.error = `HTTP error: ${response.status} ${response.statusText}`;
    }

    return data;
  }

  /**
   * List all documents
   */
  static async listDocuments(): Promise<DocumentModel[]> {
    const response = await fetch(`${API_BASE}/api/documents`);
    if (!response.ok) {
      throw new Error(`Failed to list documents: ${response.statusText}`);
    }
    const data = await response.json();
    return data.documents || [];
  }

  /**
   * Get single document
   */
  static async getDocument(id: string): Promise<DocumentModel> {
    const response = await fetch(`${API_BASE}/api/documents/${id}`);
    if (!response.ok) {
      throw new Error(`Failed to load document: ${response.statusText}`);
    }
    const data = await response.json();
    return data.document;
  }

  /**
   * Save a new document
   */
  static async createDocument(doc: {
    title: string;
    content: string;
    text_content?: string;
    word_count?: number;
  }): Promise<DocumentModel> {
    const response = await fetch(`${API_BASE}/api/documents`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(doc),
    });
    if (!response.ok) {
      throw new Error(`Failed to create document: ${response.statusText}`);
    }
    const data = await response.json();
    return data.document;
  }

  /**
   * Update an existing document
   */
  static async updateDocument(
    id: string,
    doc: {
      title?: string;
      content?: string;
      text_content?: string;
      word_count?: number;
    }
  ): Promise<DocumentModel> {
    const response = await fetch(`${API_BASE}/api/documents/${id}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(doc),
    });
    if (!response.ok) {
      throw new Error(`Failed to update document: ${response.statusText}`);
    }
    const data = await response.json();
    return data.document;
  }

  /**
   * Delete document
   */
  static async deleteDocument(id: string): Promise<boolean> {
    const response = await fetch(`${API_BASE}/api/documents/${id}`, {
      method: 'DELETE',
    });
    return response.ok;
  }

  /**
   * Download a saved document as DOCX or PDF (generated by the backend)
   */
  static async exportDocument(id: string, format: ExportFormat, fallbackName: string): Promise<void> {
    const response = await fetch(`${API_BASE}/api/documents/${id}/export?format=${format}`);
    if (!response.ok) {
      throw new Error(await errorMessage(response, `Export failed (HTTP ${response.status})`));
    }
    const blob = await response.blob();
    const disposition = response.headers.get('Content-Disposition') || '';
    const utf8Name = /filename\*=UTF-8''([^;]+)/i.exec(disposition)?.[1];
    const plainName = /filename="?([^";]+)"?/i.exec(disposition)?.[1];
    const filename = utf8Name ? decodeURIComponent(utf8Name) : plainName || `${fallbackName}.${format}`;

    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  /** Render the given editor HTML as the PDF the export would produce (nothing is saved) */
  static async previewDocument(content: string, title: string): Promise<Blob> {
    const response = await fetch(`${API_BASE}/api/documents/preview`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ content, title }),
    });
    if (!response.ok) {
      throw new Error(await errorMessage(response, `Preview failed (HTTP ${response.status})`));
    }
    return response.blob();
  }

  // ---------------------------------------------------------------------------
  // Templates
  // ---------------------------------------------------------------------------

  /**
   * Upload a PDF or DOCX to extract a reusable template. Uses XHR so upload progress can be reported;
   * `onUploadProgress` receives 0-100, then the server extracts headings with the LLM.
   */
  static uploadTemplate(
    file: File,
    onUploadProgress?: (percent: number) => void,
    templateName?: string
  ): Promise<TemplateUploadResult> {
    return new Promise((resolve, reject) => {
      const formData = new FormData();
      formData.append('file', file, file.name);
      if (templateName?.trim()) formData.append('template_name', templateName.trim());

      const xhr = new XMLHttpRequest();
      xhr.open('POST', `${API_BASE}/api/templates/upload`);
      xhr.responseType = 'json';
      xhr.upload.onprogress = (e) => {
        if (e.lengthComputable && onUploadProgress) {
          onUploadProgress(Math.round((e.loaded / e.total) * 100));
        }
      };
      xhr.onload = () => {
        const data = xhr.response as ({ success?: boolean; error?: string } & Partial<TemplateUploadResult>) | null;
        if (xhr.status >= 200 && xhr.status < 300 && data?.template) {
          resolve({ template: data.template, extraction: data.extraction! });
        } else {
          reject(new Error(data?.error || `Template upload failed (HTTP ${xhr.status})`));
        }
      };
      xhr.onerror = () => reject(new Error('Could not reach the backend. Is the Flask server running?'));
      xhr.send(formData);
    });
  }

  static async listTemplates(): Promise<TemplateSummary[]> {
    const data = await requestJson<{ templates: TemplateSummary[] }>(`/api/templates`);
    return data.templates || [];
  }

  static async getTemplate(id: string): Promise<TemplateModel> {
    const data = await requestJson<{ template: TemplateModel }>(`/api/templates/${id}`);
    return data.template;
  }

  static async renameTemplate(id: string, templateName: string): Promise<TemplateModel> {
    const data = await requestJson<{ template: TemplateModel }>(`/api/templates/${id}`, {
      method: 'PUT',
      body: JSON.stringify({ template_name: templateName }),
    });
    return data.template;
  }

  /** Deletes the template definition; documents created from it are kept. */
  static async deleteTemplate(id: string): Promise<{ detached_documents: number }> {
    return requestJson<{ detached_documents: number }>(`/api/templates/${id}`, { method: 'DELETE' });
  }

  static async addTemplateField(templateId: string, field: NewTemplateField): Promise<TemplateModel> {
    const data = await requestJson<{ template: TemplateModel }>(`/api/templates/${templateId}/fields`, {
      method: 'POST',
      body: JSON.stringify(field),
    });
    return data.template;
  }

  static async updateTemplateField(
    templateId: string,
    fieldId: string,
    update: TemplateFieldUpdate
  ): Promise<TemplateModel> {
    const data = await requestJson<{ template: TemplateModel }>(
      `/api/templates/${templateId}/fields/${fieldId}`,
      { method: 'PUT', body: JSON.stringify(update) }
    );
    return data.template;
  }

  static async deleteTemplateField(templateId: string, fieldId: string): Promise<TemplateModel> {
    const data = await requestJson<{ template: TemplateModel }>(
      `/api/templates/${templateId}/fields/${fieldId}`,
      { method: 'DELETE' }
    );
    return data.template;
  }

  /** Create a completed document linked to a template */
  static async createDocumentFromTemplate(
    templateId: string,
    doc: { title: string; content: string; text_content?: string; word_count?: number }
  ): Promise<DocumentModel> {
    const data = await requestJson<{ document: DocumentModel }>(`/api/templates/${templateId}/documents`, {
      method: 'POST',
      body: JSON.stringify(doc),
    });
    return data.document;
  }
}

async function errorMessage(response: Response, fallback: string): Promise<string> {
  try {
    const data = await response.json();
    return data?.error || fallback;
  } catch {
    return fallback;
  }
}

/** fetch + JSON with the backend's {success, error} error convention */
async function requestJson<T>(path: string, init: RequestInit = {}): Promise<T> {
  let response: Response;
  try {
    response = await fetch(`${API_BASE}${path}`, {
      ...init,
      headers: { 'Content-Type': 'application/json', Accept: 'application/json', ...(init.headers || {}) },
    });
  } catch {
    throw new Error('Could not reach the backend. Is the Flask server running?');
  }
  if (!response.ok) {
    throw new Error(await errorMessage(response, `Request failed (HTTP ${response.status})`));
  }
  return (await response.json()) as T;
}
